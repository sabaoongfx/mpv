local function juxt_volume_content()
    local vol = state.volume or 0
    local muted = state.mute or vol == 0
    local frac = math.min(100, math.max(0, vol)) / 100
    local cut = muted and 0 or frac * JUXT_CONE_W
    local fill = {}
    for _, p in ipairs(juxt_cone_polys.fill) do
        local c = juxt_clip_poly(p, cut)
        if #c >= 6 then fill[#fill + 1] = c end
    end
    local colour = "&H" .. osc_color_convert(user_opts.buttons_color) .. "&"
    local speaker = muted and juxt_icon_polys.mute or juxt_icon_polys.volume
    -- One drawing block for the whole control. libass moves the pen after each drawing block, so
    -- separate blocks would shift the later ones (the wedge ran into the fullscreen button).
    -- The speaker is scaled to 18 px here, not with \\fscx, so the wedge is not scaled too.
    -- The speaker is centred on the 28 px row (its 24 px box at 0.75 starts 5 px down).
    -- Two zero-area points at the corners of the whole control keep the drawing's bounding box fixed,
    -- so the speaker does not move as the wedge changes size.
    local x_end = math.floor((JUXT_CONE_SPEAKER_W + JUXT_CONE_W) * 8 + 0.5)
    local anchors = string.format(" m 0 0 l 0 0 m %d %d l %d %d", x_end, 28 * 8, x_end, 28 * 8)
    return string.format("{\\1c%s\\p4}%s %s%s{\\p0}", colour,
        juxt_poly_ass(speaker, 0, 5, 0.75),
        juxt_poly_ass(fill, JUXT_CONE_SPEAKER_W, 0), anchors)
end

-- click on the speaker toggles mute, click or drag on the wedge sets the volume
local function juxt_bind_volume(el)
    local dragging = false
    local function set_from_mouse()
        local mx = get_virt_mouse_pos()
        local x0 = el.hitbox.x1 + JUXT_CONE_SPEAKER_W
        local frac = math.min(1, math.max(0, (mx - x0) / JUXT_CONE_W))
        if frac > 0 then mp.set_property_bool("mute", false) end
        mp.set_property_number("volume", frac * 100)
    end
    el.eventresponder["mbtn_left_up"] = nil
    el.eventresponder["mbtn_left_down"] = function ()
        local mx = get_virt_mouse_pos()
        dragging = mx >= el.hitbox.x1 + JUXT_CONE_SPEAKER_W
        if dragging then
            set_from_mouse()
        else
            mp.command("no-osd cycle mute")
        end
    end
    el.eventresponder["mouse_move"] = function ()
        if dragging and state.active_event_source == "mbtn_left" then
            set_from_mouse()
        end
    end
end

