-- clip a flat polygon to x <= cut (Sutherland-Hodgman, one half-plane)
local function juxt_clip_poly(p, cut)
    local out = {}
    local n = #p / 2
    for i = 1, n do
        local j = i % n + 1
        local xi, yi = p[2 * i - 1], p[2 * i]
        local xj, yj = p[2 * j - 1], p[2 * j]
        local ini, inj = xi <= cut, xj <= cut
        if ini then out[#out + 1] = xi; out[#out + 1] = yi end
        if ini ~= inj then
            local t = (cut - xi) / (xj - xi)
            out[#out + 1] = cut
            out[#out + 1] = yi + t * (yj - yi)
        end
    end
    return out
end


