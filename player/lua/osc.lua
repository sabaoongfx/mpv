-- returns nil or a chapter element from the native property chapter-list
local function get_chapter(possec)
    local cl = state.chapter_list  -- sorted, get latest before possec, if any

    for n=#cl,1,-1 do
        if possec >= cl[n].time then
            return cl[n]
        end
    end
end

local function disable_thumbnail()
    if state.hover_sec == -1 then
        return
    end

    state.hover_sec = -1
    mp.set_property_native("user-data/osc/hover-sec", nil)
    mp.set_property_native("user-data/osc/draw-preview", nil)
end

local function render_elements(master_ass)
    -- when the slider is dragged or hovered and we have a target chapter name
    -- then we use it instead of the normal title. we calculate it before the
    -- render iterations because the title may be rendered before the slider.
    state.forced_title = nil
    local se, ae = state.slider_element, elements[state.active_element]
    if user_opts.chapter_fmt ~= "no" and se and (ae == se or (not ae and mouse_hit(se))) then
        if state.duration then
            local possec = get_slider_value(se) * state.duration / 100 -- of mouse pos
            local ch = get_chapter(possec)
            if ch and ch.title and ch.title ~= "" then
                state.forced_title = string.format(user_opts.chapter_fmt, ch.title)
            end
        end
    end

    local function render_element(n)
        local element = elements[n]

        if element.is_wc then
            if not state.wc_visible then return end
        else
            if not state.osc_visible then return end
        end

        local saved_animation
        if element.is_wc then
            saved_animation = state.animation
            state.animation = state.wc_animation
        end

        local style_ass = assdraw.ass_new()
        style_ass:merge(element.style_ass)
        ass_append_alpha(style_ass, element.layout.alpha, 0)

        if element.eventresponder and (state.active_element == n) then

            -- run render event functions
            if element.eventresponder.render ~= nil then
                element.eventresponder.render(element)
            end

            if mouse_hit(element) then
                -- mouse down styling
                if element.styledown then
                    style_ass:append(osc_styles.elementDown)
                end

                if element.softrepeat and state.mouse_down_counter >= 15
                    and state.mouse_down_counter % 5 == 0 then

                    element.eventresponder[state.active_event_source.."_down"](element)
                end
                state.mouse_down_counter = state.mouse_down_counter + 1
            end

        end

        local elem_ass = assdraw.ass_new()

        elem_ass:merge(style_ass)

        if element.type ~= "button" then
            elem_ass:merge(element.static_ass)
        end

        if element.type == "slider" then

            local slider_lo = element.layout.slider
            local elem_geo = element.layout.geometry
            local s_min = element.slider.min.value
            local s_max = element.slider.max.value

            -- draw pos marker
            local foH, xp
            local pos = element.slider.posF()
            local foV = slider_lo.border + slider_lo.gap
            local innerH = elem_geo.h - (2 * foV)
            local seekRanges = element.slider.seekRangesF()
            local seekRangeLineHeight = innerH / 5

            if slider_lo.stype ~= "bar" then
                foH = elem_geo.h / 2
            else
                foH = slider_lo.border + slider_lo.gap
            end

            if pos then
                xp = get_slider_ele_pos_for(element, pos)

                if slider_lo.stype ~= "bar" then
                    local r = (user_opts.seekbarhandlesize * innerH) / 2
                    ass_draw_rr_h_cw(elem_ass, xp - r, foH - r,
                                     xp + r, foH + r,
                                     r, slider_lo.stype == "diamond")
                else
                    local h = 0
                    if seekRanges and user_opts.seekrangeseparate and
                       slider_lo.rtype ~= "inverted" then
                        h = seekRangeLineHeight
                    end
                    elem_ass:rect_cw(foH, foV, xp, elem_geo.h - foV - h)

                    if seekRanges and not user_opts.seekrangeseparate and
                       slider_lo.rtype ~= "inverted" then
                        -- Punch holes for the seekRanges to be drawn later
                        for _,range in pairs(seekRanges) do
                            if range["start"] < pos then
                                local pstart = get_slider_ele_pos_for(element, range["start"])
                                local pend = xp

                                if pos > range["end"] then
                                    pend = get_slider_ele_pos_for(element, range["end"])
                                end
                                elem_ass:rect_ccw(pstart, elem_geo.h - foV - seekRangeLineHeight,
                                                  pend, elem_geo.h - foV)
                            end
                        end
                    end
                end

                if slider_lo.rtype == "slider" then
                    ass_draw_rr_h_cw(elem_ass, foH - innerH / 6, foH - innerH / 6,
                                     xp, foH + innerH / 6,
                                     innerH / 6, slider_lo.stype == "diamond", 0)
                    ass_draw_rr_h_cw(elem_ass, xp, foH - innerH / 15,
                                     elem_geo.w - foH + innerH / 15, foH + innerH / 15,
                                     0, slider_lo.stype == "diamond", innerH / 15)
                    for _,range in pairs(seekRanges or {}) do
                        local pstart = get_slider_ele_pos_for(element, range["start"])
                        local pend = get_slider_ele_pos_for(element, range["end"])
                        ass_draw_rr_h_ccw(elem_ass, pstart, foH - innerH / 21,
                                          pend, foH + innerH / 21,
                                          innerH / 21, slider_lo.stype == "diamond")
                    end
                end
            end

            if seekRanges then
                if slider_lo.rtype ~= "inverted" then
                    elem_ass:draw_stop()
                    elem_ass:merge(element.style_ass)
                    ass_append_alpha(elem_ass, element.layout.alpha, user_opts.seekrangealpha)
                    elem_ass:merge(element.static_ass)
                end

                for _,range in pairs(seekRanges) do
                    local pstart = get_slider_ele_pos_for(element, range["start"])
                    local pend = get_slider_ele_pos_for(element, range["end"])

                    if slider_lo.rtype == "slider" then
                        ass_draw_rr_h_cw(elem_ass, pstart, foH - innerH / 21,
                                         pend, foH + innerH / 21,
                                         innerH / 21, slider_lo.stype == "diamond")
                    elseif slider_lo.rtype == "line" then
                        if slider_lo.stype == "bar" then
                            elem_ass:rect_cw(pstart, elem_geo.h - foV - seekRangeLineHeight,
                                             pend, elem_geo.h - foV)
                        else
                            ass_draw_rr_h_cw(elem_ass, pstart - innerH / 8, foH - innerH / 8,
                                             pend + innerH / 8, foH + innerH / 8,
                                             innerH / 8, slider_lo.stype == "diamond")
                        end
                    elseif slider_lo.rtype == "bar" then
                        if slider_lo.stype ~= "bar" then
                            ass_draw_rr_h_cw(elem_ass, pstart - innerH / 2, foV,
                                             pend + innerH / 2, foV + innerH,
                                             innerH / 2, slider_lo.stype == "diamond")
                        elseif range["end"] >= (pos or 0) then
                            elem_ass:rect_cw(pstart, foV, pend, elem_geo.h - foV)
                        else
                            elem_ass:rect_cw(pstart, elem_geo.h - foV - seekRangeLineHeight, pend,
                                             elem_geo.h - foV)
                        end
                    elseif slider_lo.rtype == "inverted" then
                        local rlh = slider_lo.inverted_size or 1
                        if slider_lo.stype ~= "bar" then
                            ass_draw_rr_h_ccw(elem_ass, pstart, (elem_geo.h / 2) - rlh, pend,
                                              (elem_geo.h / 2) + rlh,
                                              rlh, slider_lo.stype == "diamond")
                        else
                            elem_ass:rect_ccw(pstart, (elem_geo.h / 2) - rlh, pend,
                                              (elem_geo.h / 2) + rlh)
                        end
                    end
                end
            end

            elem_ass:draw_stop()

            -- hover position indicator
            if slider_lo.hover_bar and element.slider.tooltipF ~= nil
                and mouse_hit(element) then

                local hover_val = get_slider_value(element)
                local hover_x = get_slider_ele_pos_for(element, hover_val)

                elem_ass:new_event()
                elem_ass:pos(element.hitbox.x1 + hover_x - 0.75,
                             element.hitbox.y1 + foV)
                elem_ass:an(7)
                elem_ass:append(element.layout.style)
                ass_append_alpha(elem_ass,
                    {[1] = 80, [2] = 255, [3] = 255, [4] = 255}, 0)
                elem_ass:draw_start()
                elem_ass:rect_cw(0, 0, 1.5, elem_geo.h - 2 * foV)
                elem_ass:draw_stop()
            end

            -- add tooltip
            if element.slider.tooltipF ~= nil then
                if mouse_hit(element) then
                    local sliderpos = get_slider_value(element)
                    local tooltiplabel = element.slider.tooltipF(sliderpos)

                    local an = slider_lo.tooltip_an

                    local ty

                    if an == 2 then
                        ty = element.hitbox.y1 - slider_lo.border
                    else
                        ty = element.hitbox.y1 + elem_geo.h / 2
                    end

                    local tx = get_virt_mouse_pos()
                    if slider_lo.adjust_tooltip then
                        if an == 2 then
                            if sliderpos < (s_min + 3) then
                                an = an - 1
                            elseif sliderpos > (s_max - 3) then
                                an = an + 1
                            end
                        elseif sliderpos > (s_max+s_min) / 2 then
                            an = an + 1
                            tx = tx - 5
                        else
                            an = an - 1
                            tx = tx + 10
                        end
                    end

                    -- tooltip label
                    elem_ass:new_event()
                    elem_ass:pos(tx, ty)
                    elem_ass:an(an)
                    elem_ass:append(slider_lo.tooltip_style)
                    ass_append_alpha(elem_ass, slider_lo.alpha, 0)
                    elem_ass:append(tooltiplabel)

                    local hover_sec = (state.duration or 0) * (sliderpos / 100)
                    local changed = math.abs(hover_sec - state.hover_sec) > 0.5
                    if changed then
                       mp.set_property_number("user-data/osc/hover-sec", hover_sec)
                       state.hover_sec = hover_sec
                    end

                    -- thumbnail
                    local vop = mp.get_property_native("video-out-params")
                    local draw_thumbnail = state.osd_dimensions.w > 0 and vop and changed
                    if draw_thumbnail then
                        local r_w, r_h = get_virt_scale_factor()
                        local thumb_max = math.min(user_opts.max_thumb_size,
                            math.min(state.osd_dimensions.w, state.osd_dimensions.h) * 0.25)
                        local scale = thumb_max / math.max(vop.dw, vop.dh)
                        local thumb_w = math.floor(vop.dw * scale + 0.5)
                        local thumb_h = math.floor(vop.dh * scale + 0.5)
                        local tooltip_font_size = (user_opts.layout == "box" or
                            user_opts.layout == "slimbox") and 2 or 12
                        local thumb_tx = tx
                        local thumb_ty = user_opts.layout ~= "topbar" and element.hitbox.y1 - 8 or
                            element.hitbox.y2 + tooltip_font_size + 8
                        local thumb_pad = 4
                        local thumb_margin_x = 20 / r_w
                        local thumb_margin_y = (4 + user_opts.tooltipborder) / r_h + thumb_pad
                        local thumb_x = math.min(state.osd_dimensions.w - thumb_w - thumb_margin_x,
                            math.max(thumb_margin_x, thumb_tx / r_w - thumb_w / 2))
                        local thumb_y = thumb_ty / r_h + (user_opts.layout ~= "topbar" and
                            -(thumb_h + tooltip_font_size / r_h + thumb_margin_y) or
                            thumb_margin_y)

                        local thumb_req = {
                            x = math.floor(thumb_x + 0.5), y = math.floor(thumb_y + 0.5),
                            w = math.floor(thumb_w + 0.5), h = math.floor(thumb_h + 0.5),
                            ["hover-sec"] = hover_sec,
                        }

                        local thumb_ass = assdraw.ass_new()
                        thumb_ass:new_event()
                        thumb_ass:pos(thumb_req.x, thumb_req.y)
                        thumb_ass:an(7)
                        thumb_ass:append(osc_styles.timePosBar)
                        thumb_ass:append("{\\1a&H20&}")
                        thumb_ass:draw_start()
                        thumb_ass:rect_cw(-thumb_pad, -thumb_pad,
                            thumb_req.w + thumb_pad, thumb_req.h + thumb_pad)
                        thumb_ass:draw_stop()
                        thumb_req.ass = thumb_ass.text

                        mp.set_property_native("user-data/osc/draw-preview", thumb_req)
                    end
                else
                    disable_thumbnail()
                end
            end

        elseif element.type == "button" then

            local buttontext
            if type(element.content) == "function" then
                buttontext = element.content() -- function objects
            elseif element.content ~= nil then
                buttontext = element.content -- text objects
            end

            local maxchars = element.layout.button.maxchars
            if maxchars ~= nil and #buttontext > maxchars then
                local max_ratio = 1.25  -- up to 25% more chars while shrinking
                local limit = math.max(0, math.floor(maxchars * max_ratio) - 3)
                if #buttontext > limit then
                    while (#buttontext > limit) do
                        buttontext = buttontext:gsub(".[\128-\191]*$", "")
                    end
                    buttontext = buttontext .. "..."
                end
                buttontext = string.format("{\\fscx%f}",
                    (maxchars/#buttontext)*100) .. buttontext
            end

            elem_ass:append(buttontext)
        end

        master_ass:merge(elem_ass)

        if element.is_wc then
            state.animation = saved_animation
        end
    end

    for n = 1, #elements do
        render_element(n)
    end
end


